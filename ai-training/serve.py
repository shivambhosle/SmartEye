"""
Serves the trained pothole/garbage/normal classifier over HTTP, so the
Node.js backend can call it like any other API — Node can't run PyTorch
directly, so this small FastAPI service is the bridge between the two.

Run with: uvicorn serve:app --port 8001
"""

import io
import os
from fastapi import FastAPI, File, UploadFile, HTTPException
from fastapi.middleware.cors import CORSMiddleware
import torch
import torch.nn as nn
from torchvision import transforms, models
from PIL import Image

app = FastAPI()

# Only the Node backend calls this, running on localhost — CORS is wide open
# here since this service is never exposed publicly, only called
# server-to-server from your own Express app.
app.add_middleware(CORSMiddleware, allow_origins=["*"], allow_methods=["*"], allow_headers=["*"])

device = torch.device('cuda' if torch.cuda.is_available() else 'mps' if torch.backends.mps.is_available() else 'cpu')

# Look for either issue_classifier.pt or pothole_classifier.pt (generated by train.py)
checkpoint_path = None
for candidate in ['issue_classifier.pt', 'pothole_classifier.pt']:
    dir_path = os.path.join(os.path.dirname(__file__), candidate)
    if os.path.exists(candidate):
        checkpoint_path = candidate
        break
    elif os.path.exists(dir_path):
        checkpoint_path = dir_path
        break

if checkpoint_path:
    checkpoint = torch.load(checkpoint_path, map_location=device, weights_only=False)
    class_names = checkpoint['class_names']
    model = models.mobilenet_v2(weights=None)
    model.classifier[1] = nn.Linear(model.last_channel, len(class_names))
    model.load_state_dict(checkpoint['model_state_dict'])
    model = model.to(device)
    model.eval()
else:
    checkpoint = None
    class_names = []
    model = None
    print("[serve] Notice: No model checkpoint found ('issue_classifier.pt' or 'pothole_classifier.pt'). Run train.py to generate weights.")

transform = transforms.Compose([
    transforms.Resize((224, 224)),
    transforms.ToTensor(),
    transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225]),
])

# Maps this model's own class names to the canonical SmartEye generalized categories.
# "Normal" isn't a real civic issue category, so it maps to None ("no suggestion").
CATEGORY_MAP = {
    'road_infrastructure': 'road_infrastructure',
    'street_lighting': 'street_lighting',
    'waste_sanitation': 'waste_sanitation',
    'water_drainage': 'water_drainage',
    'trees_green_infrastructure': 'trees_green_infrastructure',
    'public_property_vandalism': 'public_property_vandalism',
    'illegal_parking': 'illegal_parking',
    'Pothole': 'road_infrastructure',
    'pothole': 'road_infrastructure',
    'Garbage': 'waste_sanitation',
    'garbage': 'waste_sanitation',
    'Normal': None,
    'normal': None,
}


@app.post('/predict')
async def predict(image: UploadFile = File(...)):
    if model is None:
        raise HTTPException(status_code=503, detail="Model checkpoint not found. Run train.py first.")

    contents = await image.read()
    img = Image.open(io.BytesIO(contents)).convert('RGB')
    input_tensor = transform(img).unsqueeze(0).to(device)

    with torch.no_grad():
        outputs = model(input_tensor)
        probabilities = torch.softmax(outputs, dim=1)[0]
        predicted_idx = torch.argmax(probabilities).item()

    predicted_class = class_names[predicted_idx]
    confidence = probabilities[predicted_idx].item()

    return {
        'rawClass': predicted_class,
        'category': CATEGORY_MAP.get(predicted_class),
        'confidence': round(confidence, 4),
    }


@app.get('/health')
async def health():
    return {
        'status': 'ok' if model is not None else 'no_model_checkpoint',
        'classes': class_names,
        'checkpoint': checkpoint_path,
        'device': str(device),
    }